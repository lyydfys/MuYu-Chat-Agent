from pathlib import Path
import json
import re

REPO = Path(__file__).resolve().parents[2]
ROOT = REPO / 'app/src/main/java/com/muyuchat/mca'
source = (ROOT / 'MainUiState.kt').read_text(encoding='utf-8-sig')
constructor = source.split('data class MainUiState(', 1)[1].split('\n)', 1)[0]
types = dict(re.findall(r'^    val (\w+): (.+?) = ', constructor, re.M))
imports = '\n'.join(line for line in source.splitlines() if line.startswith('import '))
groups = json.loads(Path(__file__).with_name('state_write_authorities.json').read_text(encoding='utf-8'))

(ROOT / 'UiStateFields.kt').write_text(
    'package com.muyuchat.mca\n\n' + imports + '\n\n'
    '// Generated by tools/architecture/generate_state_fields.py; authority manifest is reviewed.\n'
    '/** One immutable CAS input for read-only cross-domain decisions. Writes use concrete fields. */\n'
    'interface UiStateFields { val snapshot: MainUiState }\n\n' +
    '\n\n'.join(f'val UiStateFields.{name}: {kind}\n    get() = snapshot.{name}' for name, kind in types.items()) + '\n', encoding='utf-8')
factories = []
for name, fields in groups.items():
    fields = list(dict.fromkeys(fields))
    unknown = set(fields) - types.keys()
    if unknown:
        raise ValueError((name, unknown))
    body = 'package com.muyuchat.mca\n\n' + imports + '\n\n'
    body += '// Generated by tools/architecture/generate_state_fields.py; authority manifest is reviewed.\n'
    body += '/** Fixed write authority; every other application field is read-only. */\n'
    body += f'data class {name}(\n    override val snapshot: MainUiState,\n'
    body += ''.join(f'    val {field}: {types[field]} = snapshot.{field},\n' for field in fields)
    body += ') : UiStateFields\n\n'
    body += f'fun MainUiState.to{name}(): {name} = {name}(this)\n\n'
    body += f'fun {name}.mergeInto(current: MainUiState): MainUiState = current.copy(\n'
    body += ''.join(f'    {field} = {field},\n' for field in fields)
    body += ')\n'
    (ROOT / (name + '.kt')).write_text(body, encoding='utf-8')
    factory = name.removesuffix('Fields')
    factory = factory[:1].lower() + factory[1:] + 'Writer'
    factories.append(f'internal fun UiStateStore.{factory}(): UiStateWriter<{name}> = writer(\n    project = {{ it.to{name}() }},\n    merge = {{ current, fields -> fields.mergeInto(current) }},\n)')

# Pure construction belongs to composition; business consumers cannot select a wider writer.
(ROOT / 'composition' / 'UiStateDomainWriters.kt').write_text(
    'package com.muyuchat.mca.composition\n\nimport com.muyuchat.mca.*\n\n' + '\n\n'.join(factories) + '\n', encoding='utf-8')
print(f'Generated {len(groups)} fixed field authorities, {len(types)} read-only root projections')
