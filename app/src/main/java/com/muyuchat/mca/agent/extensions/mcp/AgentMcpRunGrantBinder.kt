package com.muyuchat.mca.agent.extensions.mcp

import com.muyuchat.core.agent.contract.AgentNetworkPolicy
import com.muyuchat.core.agent.contract.AgentRun
import com.muyuchat.core.agent.contract.AgentTask
import com.muyuchat.mca.agent.security.AgentEgressGrantOutcome
import com.muyuchat.mca.agent.security.AgentEgressGrantRequest
import com.muyuchat.mca.agent.security.AgentEgressGrantStore
import com.muyuchat.mca.agent.security.AgentEgressScope
import com.muyuchat.mca.agent.security.AgentEgressTransport
import com.muyuchat.mca.agent.security.AgentNetworkEgressPolicy
import java.security.MessageDigest
import kotlinx.coroutines.CancellationException

/** One server whose durable authorization could not be turned into a run-scoped egress grant. */
data class AgentMcpGrantBindingFailure(
    val serverId: String,
    val reasonCode: String
)

/**
 * Typed result of binding durable server authorizations to one run.
 *
 * This is intentionally a value, not an exception: a single unusable server must not abort the run
 * or hide the other server. [skippedReasonCode] is set when the run policy itself excludes MCP
 * (offline/LOCAL_ONLY, task mismatch or an unreadable registry), in which case no store write is
 * attempted at all. A non-empty [failures] list never means "partially connected": the catalog
 * provider simply has fewer (or zero) MCP tools for this run and keeps built-ins/Skills intact.
 */
data class AgentMcpGrantBindingReport(
    val boundServerIds: List<String>,
    val failures: List<AgentMcpGrantBindingFailure>,
    val skippedReasonCode: String? = null
) {
    init {
        require(boundServerIds == boundServerIds.distinct().sorted()) {
            "bound MCP server ids must be sorted and unique"
        }
        require(failures.map { it.serverId } == failures.map { it.serverId }.distinct().sorted()) {
            "MCP binding failures must be sorted and unique per server"
        }
        require(skippedReasonCode == null || (boundServerIds.isEmpty() && failures.isEmpty())) {
            "a skipped MCP binding must not also report bound or failed servers"
        }
    }
}

/**
 * Run-start binding of durable, user-authorized MCP servers to run-scoped egress grants.
 *
 * Contract:
 * - only an enabled server that still carries the explicit [AgentMcpAuthorization] recorded by the
 *   user's Agent-network action is considered; a missing/revoked authorization is never guessed;
 * - the authorization must still describe the server's exact canonical origin and transport, so an
 *   endpoint change since the user authorized it makes the authorization stale (fail closed);
 * - every bound grant is generated by [AgentNetworkEgressPolicy.createGrant] with the authorization's
 *   explicit data classes (PRIVATE is mandatory), the exact origin and no source wildcard;
 * - a run that is LOCAL_ONLY/offline, or whose task does not match the run, binds nothing;
 * - a store/policy failure for one server is recorded as a typed [AgentMcpGrantBindingFailure] and
 *   never blocks another server, run start or the built-in catalog. Cancellation always propagates.
 *
 * This class does not open a socket and does not call the model. It is the only production caller of
 * `AgentNetworkEgressPolicy.createGrant`; the catalog provider consumes only grants that exist.
 */
class AgentMcpRunGrantBinder(
    private val serverStore: AgentMcpServerStore,
    private val grantStore: AgentEgressGrantStore,
    private val policy: AgentNetworkEgressPolicy = AgentNetworkEgressPolicy()
) {
    suspend fun bind(run: AgentRun, task: AgentTask): AgentMcpGrantBindingReport {
        if (run.taskId != task.taskId) return skipped("MCP_GRANT_TASK_MISMATCH")
        if (run.policy.networkPolicy != AgentNetworkPolicy.NETWORK_ENABLED || run.policy.offlineForced) {
            return skipped("MCP_GRANT_POLICY_OFFLINE")
        }
        val load = try {
            serverStore.load()
        } catch (cancelled: CancellationException) {
            throw cancelled
        } catch (_: Throwable) {
            return skipped("MCP_GRANT_SERVER_STORE_UNAVAILABLE")
        }
        if (load is AgentMcpServerLoad.Corrupt) return skipped(load.reasonCode)
        val candidates = (load as AgentMcpServerLoad.Loaded).servers.filter { server ->
            server.enabled && server.allowAgentNetwork && server.agentAuthorization != null
        }
        if (candidates.isEmpty()) return skipped("MCP_GRANT_NO_AUTHORIZED_SERVER")

        val scope = AgentEgressScope(
            runId = run.runId,
            networkPolicy = run.policy.networkPolicy,
            policyVersion = run.policy.policyVersion
        )
        val bound = ArrayList<String>(candidates.size)
        val failures = ArrayList<AgentMcpGrantBindingFailure>()
        for (server in candidates) {
            when (val outcome = bindServer(scope, server)) {
                is BindingOutcome.Bound -> bound += server.serverId
                is BindingOutcome.Failed -> failures += AgentMcpGrantBindingFailure(
                    server.serverId,
                    outcome.reasonCode
                )
            }
        }
        return AgentMcpGrantBindingReport(
            boundServerIds = bound.sorted(),
            failures = failures.sortedWith(compareBy({ it.serverId }, { it.reasonCode }))
        )
    }

    private suspend fun bindServer(scope: AgentEgressScope, server: AgentMcpServerRecord): BindingOutcome {
        val authorization = server.agentAuthorization
            ?: return BindingOutcome.Failed(AUTHORIZATION_MISSING)
        if (!authorization.coversProjectedTools()) {
            return BindingOutcome.Failed(AUTHORIZATION_SCOPE_INSUFFICIENT)
        }
        val origin = when (val check = AgentMcpEndpointPolicy.check(server.endpoint, server.allowLocal)) {
            is AgentMcpEndpointCheck.Allowed -> check.origin
            is AgentMcpEndpointCheck.Rejected -> return BindingOutcome.Failed(check.code)
        }
        if (origin != authorization.origin ||
            authorization.transport != AgentMcpServerRecord.transportOf(server.allowLocal)
        ) {
            return BindingOutcome.Failed(AUTHORIZATION_STALE)
        }
        val request = AgentEgressGrantRequest(
            grantId = grantIdFor(scope.runId, server.serverId),
            transport = authorization.transport,
            origin = origin,
            dataClasses = authorization.dataClasses,
            sourceIds = emptySet()
        )
        val granted = when (val created = policy.createGrant(scope, request)) {
            is AgentEgressGrantOutcome.Created -> created.grant
            is AgentEgressGrantOutcome.Rejected -> return BindingOutcome.Failed(
                created.error.code.ifBlank { GRANT_POLICY_REJECTED }
            )
        }
        return try {
            when (val persisted = grantStore.create(granted)) {
                is AgentEgressGrantOutcome.Created -> BindingOutcome.Bound
                is AgentEgressGrantOutcome.Rejected -> BindingOutcome.Failed(
                    persisted.error.code.ifBlank { GRANT_PERSIST_REJECTED }
                )
            }
        } catch (cancelled: CancellationException) {
            throw cancelled
        } catch (_: Throwable) {
            // A storage outage must never turn into an implicit "always allow" or crash the run.
            BindingOutcome.Failed(GRANT_PERSIST_FAILED)
        }
    }

    private fun skipped(reasonCode: String): AgentMcpGrantBindingReport =
        AgentMcpGrantBindingReport(emptyList(), emptyList(), reasonCode)

    private sealed interface BindingOutcome {
        data object Bound : BindingOutcome

        data class Failed(val reasonCode: String) : BindingOutcome
    }

    companion object {
        const val AUTHORIZATION_MISSING: String = "MCP_GRANT_AUTHORIZATION_MISSING"
        const val AUTHORIZATION_SCOPE_INSUFFICIENT: String = "MCP_GRANT_SCOPE_INSUFFICIENT"
        const val AUTHORIZATION_STALE: String = "MCP_GRANT_AUTHORIZATION_STALE"
        const val GRANT_POLICY_REJECTED: String = "MCP_GRANT_POLICY_REJECTED"
        const val GRANT_PERSIST_REJECTED: String = "MCP_GRANT_PERSIST_REJECTED"
        const val GRANT_PERSIST_FAILED: String = "MCP_GRANT_PERSIST_FAILED"

        /**
         * Deterministic per (run, server) identity: repeating a bind for the same execution replaces
         * the same row only when the frozen scope is identical, and never grows an unbounded set.
         */
        fun grantIdFor(runId: String, serverId: String): String {
            val digest = MessageDigest.getInstance("SHA-256")
            val hash = digest.digest("$runId\u0000$serverId".toByteArray(Charsets.UTF_8))
            return "mcp-grant-" + hash.take(20).joinToString("") { "%02x".format(it) }
        }
    }
}
