/*
 * dsh_pty.c - real POSIX pseudo-terminal primitive for the MCA DSH runtime (D12).
 *
 * Why this file exists: the referenced Android host "tries /dev/ptmx and then scans
 * /dev/pts/0..63", has no unlock/ptsname/ioctl proof that the slave belongs to its master, and
 * makes resize a no-op. That is not a PTY. This file allocates a *pair*:
 *
 *   posix_openpt() -> grantpt() -> unlockpt() -> ptsname_r(master)  (the kernel names OUR slave,
 *   no scanning, no guessing)
 *   fork() -> setsid() -> ioctl(slave, TIOCSCTTY) -> dup2(slave, 0/1/2) -> execve()
 *
 * The child owns one session and is the session/foreground process-group leader, so:
 *  - control characters (^C, ^Z, ^D) are generated by the tty line discipline over the master;
 *  - ioctl(TIOCSWINSZ) on the master makes the kernel deliver SIGWINCH to the foreground group;
 *  - background jobs and job control behave like a normal terminal.
 *
 * The JVM side (DshPtyNative.kt) owns the lifecycle: open -> attach -> read/write/resize ->
 * close(grace -> SIGKILL). Every error path returns errno to Kotlin instead of pretending success.
 *
 * Deliberately NOT implemented here: /dev/pts scanning (cannot prove ownership), a fake
 * "isatty" shim, or a resize that silently does nothing. A pipe fallback lives in Kotlin and is
 * reported as NON_PTY, never as a PTY.
 */

