package com.muyuchat.core.dsh.runtime.config

import java.io.File

/**
 * Fixed composition of the official DSH configuration plus the MCA-managed overlay.
 *
 * The order is the official loader's, not an MCA invention: the payload template is the base,
 * the profile composition (`profiles/web/cordis.yml`) names the bundles, and the home
 * `cordis.patch.yml` is the documented patch layer that both the user and MCA may write. MCA owns
 * only an explicit allowlist of rows in that patch; every other row is owned by the user or by the
 * official plugin manager and must survive a reseed.
 */
internal enum class DshConfigLayer(val detail: String) {
    PAYLOAD_TEMPLATE(
        "payload dshhome template: profiles/web/{cordis.yml,package.json,pnpm-workspace.yaml}, settings.yaml"
    ),
    HOME_PROFILE(
        "home profiles/web: after the first seed the official plugin manager owns package.json and pnpm-workspace.yaml"
    ),
    MCA_MANAGED_OVERLAY(
        "home cordis.patch.yml rows generated by DshGatewayConfigSeeder (platform rows + MCA provider)"
    ),
    USER_SETTINGS("home settings.yaml: official user settings, never rewritten by a reseed"),
    USER_PROFILE_EDITS("home cordis.yml / user patch rows: never overwritten, preserved by merge")
}

/** Rows inside `cordis.patch.yml` that MCA owns and rewrites on every DSH host generation. */
internal object DshManagedOverlay {
    const val HEADER_MARKER = "# MCA-owned DSH overlay."

    val MANAGED_ROW_IDS: Set<String> = linkedSetOf(
        "bash-sandbox",
        "sandbox",
        "pwsh-sandbox",
        "session-log-download",
        "session-telemetry-otel",
        "permission",
        "workspace-controller",
        "llm-pi-ai",
        "insert"
    )

    /** Official provider rows MCA must never disable or rewrite. */
    val OFFICIAL_PROVIDER_MARKERS: List<String> = listOf(
        "deepseek-account",
        "llm-deepseek-account"
    )

    /**
     * The five official mobile tool packages the pinned reference overlay inserts. MCA keeps them
     * enabled: the capability bridge replaces the reference App-side HTTP implementation they call,
     * never the DSH-side tool definitions/schemas the agent needs.
     */
    val MOBILE_TOOL_PACKAGES: List<Pair<String, String>> = listOf(
        "tool-shizuku" to "@deepseek-ai/dsh-tool-shizuku",
        "tool-android" to "@deepseek-ai/dsh-tool-android",
        "tool-accessibility" to "@deepseek-ai/dsh-tool-accessibility",
        "tool-vscreen" to "@deepseek-ai/dsh-tool-vscreen",
        "tool-browser" to "@deepseek-ai/dsh-tool-browser"
    )

    /**
     * True when this block is regenerated by MCA.
     *
     * `insert` is special: MCA owns only the insert block that carries its own `bash-local`
     * provider. A user's separate insert block is preserved verbatim, because dropping it would
     * silently delete their patch.
     *
     * [managedIds] adds the rows that are owned *per generation* rather than statically: the
     * `dsh-mcp-client` rows the seeder composed from `<DSH_HOME>/mcp-servers.json` (their ids come
     * from the declaration file) plus the ids of rows a previous generation marked as its own, so a
     * server removed from that file also loses its row.
     */
    fun isManagedBlock(
        id: String?,
        raw: String? = null,
        managedIds: Set<String> = MANAGED_ROW_IDS
    ): Boolean {
        if (id == null) return false
        if (id == INSERT_ROW_ID) {
            // The managed platform insert carries the MCA marker (and, in advisory mode,
            // bash-local); an MCP insert is proven by its own MCA-owned row marker so a
            // regenerated declaration never duplicates its rows.
            return raw == null ||
                raw.contains(MANAGED_INSERT_MARKER) ||
                raw.contains("id: bash-local") ||
                raw.contains(DshMcpOverlayRows.OWNED_ROW_MARKER)
        }
        return id in managedIds
    }

    const val INSERT_ROW_ID = "insert"

    /** Stable comment inside the MCA-owned insert block, independent of the shell provider. */
    const val MANAGED_INSERT_MARKER = "mca:managed-insert"
}

/** Result of merging the previous on-disk overlay with a freshly generated one. */
internal data class DshOverlayMergePlan(
    val text: String,
    /** Non-managed block ids (or `(unnamed row)`) preserved from the previous file. */
    val preservedUserRows: List<String>,
    /** Managed rows that existed in the previous file and were regenerated. */
    val managedConflicts: List<String>,
    /** The previous file could not be parsed as a patch sequence and is replaced. */
    val previousWasCorrupt: Boolean,
    /** The previous file must be kept as a sibling backup before it is replaced. */
    val backupPrevious: Boolean
)

/**
 * Three-way merge of the MCA-owned overlay.
 *
 * - old MCA value: the `overlaySha256` recorded in the template marker;
 * - current file: whatever is on disk (possibly edited by the user or by an older build);
 * - new value: the freshly generated managed rows.
 *
 * Only rows whose id is in [DshManagedOverlay.MANAGED_ROW_IDS] (plus the per-generation
 * [managedIds] the seeder passes for its `dsh-mcp-client` rows) are regenerated. Every other row is
 * preserved verbatim and appended after the regenerated block, so a user or another owner's patch
 * is never silently dropped. A file that cannot be parsed as a YAML patch sequence is treated as
 * corrupt: it is backed up next to the target and replaced by the valid generated overlay instead
 * of being merged into garbage.
 */
internal object DshManagedOverlayMerge {

    fun plan(
        previous: String?,
        generated: String,
        managedIds: Set<String> = DshManagedOverlay.MANAGED_ROW_IDS
    ): DshOverlayMergePlan {
        if (previous.isNullOrBlank()) {
            return DshOverlayMergePlan(
                text = generated,
                preservedUserRows = emptyList(),
                managedConflicts = emptyList(),
                previousWasCorrupt = false,
                backupPrevious = false
            )
        }
        val parsed = parse(previous)
            ?: return DshOverlayMergePlan(
                text = generated,
                preservedUserRows = emptyList(),
                managedConflicts = emptyList(),
                previousWasCorrupt = true,
                backupPrevious = true
            )
        val managed = parsed.filter { DshManagedOverlay.isManagedBlock(it.id, it.raw, managedIds) }
        val preserved = parsed.filterNot { DshManagedOverlay.isManagedBlock(it.id, it.raw, managedIds) }
        if (preserved.isEmpty()) {
            return DshOverlayMergePlan(
                text = generated,
                preservedUserRows = emptyList(),
                managedConflicts = managed.mapNotNull { it.id },
                previousWasCorrupt = false,
                backupPrevious = false
            )
        }
        val text = buildString {
            append(generated.trimEnd())
            append('\n')
            appendLine("# Preserved rows from the previous overlay that MCA does not own.")
            preserved.forEach { block ->
                append(block.raw.trimEnd())
                append('\n')
            }
        }
        return DshOverlayMergePlan(
            text = text,
            preservedUserRows = preserved.map { it.id ?: UNNAMED_ROW },
            managedConflicts = managed.mapNotNull { it.id },
            previousWasCorrupt = false,
            backupPrevious = false
        )
    }

    private const val UNNAMED_ROW = "(unnamed row)"

    internal data class OverlayBlock(val id: String?, val raw: String)

    /**
     * Splits a patch file into top-level sequence blocks. Returns null when the file is not a patch
     * sequence at all (a non-comment line before the first `- ` row, or an indented orphan line),
     * which is the only condition that justifies replacing the file wholesale.
     */
    internal fun parse(text: String): List<OverlayBlock>? {
        val blocks = ArrayList<OverlayBlock>()
        val preamble = ArrayList<String>()
        var current: StringBuilder? = null
        for (line in text.lines()) {
            val isRowStart = line.startsWith("- ")
            if (isRowStart) {
                current?.let {
                    blocks += OverlayBlock(blockIdOf(it.toString()), it.toString())
                }
                current = StringBuilder().append(line).append('\n')
                continue
            }
            val isBlank = line.isBlank()
            val isComment = line.trimStart().startsWith("#")
            if (current == null) {
                if (isBlank || isComment) {
                    preamble += line
                    continue
                }
                // A mapping key or indented content before the first sequence row is not a patch.
                return null
            }
            if (!isComment && !isBlank && !line.startsWith(" ") && !line.startsWith("\t")) {
                // A second top-level document/mapping after a patch sequence is not supported.
                return null
            }
            current.append(line).append('\n')
        }
        current?.let { blocks += OverlayBlock(blockIdOf(it.toString()), it.toString()) }
        return blocks
    }

    private fun blockIdOf(raw: String): String? {
        val first = raw.lineSequence().firstOrNull() ?: return null
        val body = first.removePrefix("- ").trim()
        if (body == "insert:" || body == "insert") return "insert"
        if (!body.startsWith("id:")) return null
        val value = body.removePrefix("id:").trim().trim('"', '\'')
        return value.ifEmpty { null }
    }
}

/** Provider states the host may show for one DSH host generation. */
internal sealed interface DshConfigProviderState {
    /** MCA gateway bound and at least one model advertised. */
    data class McaBound(val baseUrl: String, val modelCount: Int) : DshConfigProviderState

    /** MCA gateway bound but the honest catalog is empty (a legal state, not an error). */
    data class McaCatalogEmpty(val baseUrl: String) : DshConfigProviderState

    /** Account-only generation: no MCA gateway exists, so no MCA provider row is written. */
    data object McaNotBound : DshConfigProviderState
}

/** Typed, token-free report of one seed. */
internal data class DshSeedReport(
    val provider: DshConfigProviderState,
    val preservedUserRows: List<String>,
    val managedConflicts: List<String>,
    val previousOverlayBackedUp: Boolean,
    val overlaySha256: String,
    /** Row ids of the `dsh-mcp-client` rows this generation wrote (declaration file order). */
    val mcpServerRows: List<String> = emptyList(),
    /** Value-free refusals from `<DSH_HOME>/mcp-servers.json`; empty when absent or fully valid. */
    val mcpDiagnostics: List<DshMcpConfigDiagnostic> = emptyList(),
    /** Whether this generation's shell commands are kernel-confined or honestly advisory. */
    val sandboxEnforcement: DshSandboxEnforcement
)

/** Facts read from the generated overlay; used to refuse writing a dishonest configuration. */
internal data class DshComposedConfigFacts(
    val mcaProviderPresent: Boolean,
    val mcaProviderDisabled: Boolean,
    val mcaBaseUrl: String?,
    val mcaBaseUrlIsLoopback: Boolean,
    val mcaModelsDeclared: Int,
    val mcaModelsEmptyArray: Boolean,
    val bashSandboxDisabled: Boolean,
    /** The `sandbox` provider carries an absolute MCA Landlock `runnerCommand`. */
    val sandboxRunnerPath: String?,
    /** The overlay records the selected enforcement mode in its machine-checkable marker. */
    val sandboxKernelMarker: Boolean,
    val sandboxAdvisoryMarker: Boolean,
    val pwshSandboxDisabled: Boolean,
    val sessionLogDownloadDisabled: Boolean,
    val telemetryDisabled: Boolean,
    val bashLocalInserted: Boolean,
    /** Implied official tool packages whose exact insert row is present in the overlay. */
    val insertedMobileTools: Set<String>,
    /** True when the official `sandbox` service is explicitly disabled (it must never be). */
    val sandboxServiceDisabled: Boolean,
    val permissionDefaultPreset: String?,
    val copiesApprovalNever: Boolean,
    val workspaceDocumentsDirectory: String?,
    val touchesOfficialAccountProvider: Boolean,
    val touchesReferenceDangerDefault: Boolean
)

internal object DshComposedConfigInspector {

    fun inspect(overlay: String): DshComposedConfigFacts {
        val lines = overlay.lines()
        val mcaIndex = lines.indexOfFirst { it.trim() == "- id: llm-pi-ai" }
        val mcaBlock = if (mcaIndex >= 0) {
            lines.drop(mcaIndex + 1).takeWhile { !it.startsWith("- ") && !it.startsWith("- insert:") }
        } else {
            emptyList()
        }
        val mcaDisabled = mcaIndex >= 0 &&
            lines.getOrNull(mcaIndex + 1)?.trim() == "disabled: true"
        val baseUrl = mcaBlock.firstOrNull { it.trim().startsWith("baseURL:") }
            ?.trim()
            ?.removePrefix("baseURL:")
            ?.trim()
            ?.trim('"', '\'')
            ?.takeIf { it.isNotEmpty() }
        val modelRows = mcaBlock.count { it.trimStart().startsWith("- id:") }
        val emptyModels = mcaBlock.any { it.trim() == "models: []" }
        val preset = lines.firstOrNull { it.trim().startsWith("defaultPreset:") }
            ?.trim()
            ?.removePrefix("defaultPreset:")
            ?.trim()
        val documents = lines.firstOrNull { it.trim().startsWith("documentsDirectory:") }
            ?.trim()
            ?.removePrefix("documentsDirectory:")
            ?.trim()
            ?.trim('"', '\'')
        val runnerPath = RUNNER_COMMAND_PATTERN.find(overlay)
            ?.groupValues
            ?.get(1)
            ?.trim()
            ?.trim('"', '\'')
            ?.takeIf { File(it).isAbsolute }
        return DshComposedConfigFacts(
            mcaProviderPresent = mcaIndex >= 0,
            mcaProviderDisabled = mcaDisabled,
            mcaBaseUrl = baseUrl,
            mcaBaseUrlIsLoopback = baseUrl?.let(::isConcreteLoopbackBaseUrl) ?: false,
            mcaModelsDeclared = modelRows,
            mcaModelsEmptyArray = emptyModels,
            bashSandboxDisabled = blockDisabled(lines, "bash-sandbox"),
            sandboxRunnerPath = runnerPath,
            sandboxKernelMarker = overlay.contains("# mca-sandbox: kernel"),
            sandboxAdvisoryMarker = overlay.contains("# mca-sandbox: advisory"),
            pwshSandboxDisabled = blockDisabled(lines, "pwsh-sandbox"),
            sessionLogDownloadDisabled = blockDisabled(lines, "session-log-download"),
            telemetryDisabled = blockDisabled(lines, "session-telemetry-otel"),
            bashLocalInserted = overlay.contains("- insert:") && overlay.contains("id: bash-local"),
            insertedMobileTools = DshManagedOverlay.MOBILE_TOOL_PACKAGES
                .filter { (id, name) -> overlay.contains("    - id: $id\n      name: '$name'") }
                .map { it.first }
                .toSet(),
            sandboxServiceDisabled = lines.indices.any { index ->
                lines[index].trim() == "- id: sandbox" &&
                    lines.getOrNull(index + 1)?.trim() == "disabled: true"
            },
            permissionDefaultPreset = preset,
            copiesApprovalNever = overlay.contains("approval: never"),
            workspaceDocumentsDirectory = documents,
            touchesOfficialAccountProvider = DshManagedOverlay.OFFICIAL_PROVIDER_MARKERS.any { marker ->
                lines.any { line ->
                    val trimmed = line.trim()
                    (trimmed.startsWith("id:") || trimmed.startsWith("- id:")) && trimmed.contains(marker)
                }
            },
            touchesReferenceDangerDefault = overlay.contains("danger-full-access")
        )
    }

    /**
     * Honesty gate for one generated overlay. A violation means the seeder must refuse to publish
     * the file: a dishonest overlay (fake endpoint, disabled official provider, dropped platform
     * row) is worse than a typed boot failure.
     */
    fun violations(
        facts: DshComposedConfigFacts,
        requireMcaProvider: Boolean,
        expectKernelSandbox: Boolean = false
    ): List<String> = buildList {
        if (facts.permissionDefaultPreset != "workspace-write") {
            add("the MCA permission preset must stay workspace-write")
        }
        if (facts.copiesApprovalNever) add("approval: never must never be copied")
        if (expectKernelSandbox) {
            if (facts.bashSandboxDisabled) {
                add("bash-sandbox must stay enabled when the Landlock runner is usable")
            }
            if (facts.bashLocalInserted) {
                add("the advisory bash-local provider must not replace bash-sandbox when the runner is usable")
            }
            if (facts.sandboxRunnerPath == null) {
                add("the sandbox provider must carry an absolute Landlock runnerCommand")
            }
            if (!facts.sandboxKernelMarker) {
                add("the overlay must record the kernel sandbox fact")
            }
        } else {
            if (!facts.bashSandboxDisabled) {
                add("bash-sandbox must be disabled when no Landlock runner is usable on this device")
            }
            if (!facts.bashLocalInserted) {
                add("bash-local must be the ctx.shell provider when shell writes are advisory")
            }
            if (facts.sandboxRunnerPath != null) {
                add("an advisory overlay must not advertise a kernel runnerCommand")
            }
            if (!facts.sandboxAdvisoryMarker) {
                add("the overlay must mark the workspace-write preset as advisory")
            }
        }
        if (!facts.pwshSandboxDisabled) add("pwsh-sandbox must stay disabled on Android")
        if (!facts.sessionLogDownloadDisabled) add("session-log-download must stay disabled")
        if (!facts.telemetryDisabled) add("session-telemetry-otel must stay disabled")
        if (facts.sandboxServiceDisabled) {
            add("the official sandbox service must stay enabled: ptc-runtime injects it")
        }
        val missingTools = DshManagedOverlay.MOBILE_TOOL_PACKAGES.map { it.first }
            .filterNot { it in facts.insertedMobileTools }
        if (missingTools.isNotEmpty()) {
            add("the five official mobile tool packages must stay inserted (missing ${missingTools.joinToString(",")})")
        }
        if (facts.workspaceDocumentsDirectory.isNullOrBlank()) {
            add("the official workspace controller needs an explicit documentsDirectory")
        }
        if (facts.touchesOfficialAccountProvider) {
            add("the official DeepSeek account provider must not be modified by MCA")
        }
        if (requireMcaProvider) {
            if (!facts.mcaProviderPresent) {
                add("the MCA provider row is missing although a gateway endpoint was bound")
            } else {
                if (facts.mcaProviderDisabled) add("llm-pi-ai must not be disabled")
                if (facts.mcaBaseUrl == null) {
                    add("the MCA provider must carry a concrete baseURL")
                } else if (!facts.mcaBaseUrlIsLoopback) {
                    add("the MCA baseURL must be a concrete loopback endpoint")
                }
                if (facts.mcaModelsDeclared == 0 && !facts.mcaModelsEmptyArray) {
                    add("an empty MCA catalog must be declared as models: [] instead of YAML null")
                }
            }
        } else {
            if (facts.mcaProviderPresent) {
                add("an account-only generation must not advertise an unbound MCA provider")
            }
        }
    }

    private val RUNNER_COMMAND_PATTERN = Regex(
        """runnerCommand:\s*\n\s*-\s*["']?([^"'\n]+)["']?"""
    )

    private fun blockDisabled(lines: List<String>, id: String): Boolean {
        val index = lines.indexOfFirst { it.trim() == "- id: $id" }
        if (index < 0) return false
        return lines.getOrNull(index + 1)?.trim() == "disabled: true"
    }

    private fun isConcreteLoopbackBaseUrl(value: String): Boolean {
        val uri = runCatching { java.net.URI(value) }.getOrNull() ?: return false
        if (!uri.scheme.equals("http", ignoreCase = true)) return false
        val host = uri.host ?: return false
        if (host != "127.0.0.1" && host != "::1" && host != "localhost") return false
        return uri.port in 1..65535
    }
}



